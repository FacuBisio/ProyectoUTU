  AUTO_INCREMENT = 13;

ALTER TABLE `evento`
  DROP FOREIGN KEY `FK_EVENTO_LUGAR`;

ALTER TABLE `evento`
  DROP FOREIGN KEY `FK_EVENTO_USUARIO`;

ALTER TABLE `evento`
  ADD CONSTRAINT `FK_EVENTO_LUGAR`
    FOREIGN KEY (`ID_LUGAR`) REFERENCES `lugar` (`ID_LUGAR`) ON DELETE CASCADE,
  ADD CONSTRAINT `FK_EVENTO_USUARIO`
    FOREIGN KEY (`ID_USUARIO`) REFERENCES `usuario` (`ID_USUARIO`) ON DELETE CASCADE;

ALTER TABLE `comentario`
  DROP FOREIGN KEY `FK_COMENTARIO_USUARIO`;

ALTER TABLE `comentario`
  ADD CONSTRAINT `FK_COMENTARIO_USUARIO`
    FOREIGN KEY (`ID_USUARIO`) REFERENCES `usuario` (`ID_USUARIO`) ON DELETE CASCADE;

ALTER TABLE `lugar`
  ADD CONSTRAINT `CHK_LUGAR_COORDENADAS` CHECK (
    (`LATITUD` IS NULL AND `LONGITUD` IS NULL)
    OR (
      `LATITUD` IS NOT NULL AND `LONGITUD` IS NOT NULL
      AND `LATITUD` BETWEEN -90 AND 90
      AND `LONGITUD` BETWEEN -180 AND 180
    )
  );

ALTER TABLE `evento`
  ADD CONSTRAINT `CHK_EVENTO_COORDENADAS` CHECK (
    (`LATITUD` IS NULL AND `LONGITUD` IS NULL)
    OR (
      `LATITUD` IS NOT NULL AND `LONGITUD` IS NOT NULL
      AND `LATITUD` BETWEEN -90 AND 90
      AND `LONGITUD` BETWEEN -180 AND 180
    )
  );
